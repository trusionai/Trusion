#!/usr/bin/env python3
"""Static triage of every `.innerHTML` sink in the ORIGINAL prototype (reference/index-9.original.html).
Heuristic, not a proof: it classifies each sink and lists ${...} interpolations that are not wrapped in esc() and do not look numeric.
Output: docs/XSS-AUDIT-ORIGINAL.md (generated)."""
import re, sys, collections
SRC = sys.argv[1]; OUT = sys.argv[2]
text = open(SRC, encoding='utf-8').read()
lines = text.split('\n')

def rhs_after(pos):
    """Return the right-hand-side expression text starting at pos until the statement's ';' at depth 0 (aware of quotes/backticks)."""
    i, depth, out = pos, 0, []
    q = None
    while i < len(text) and i - pos < 6000:
        c = text[i]
        if q:
            out.append(c)
            if c == '\\': out.append(text[i+1]); i += 2; continue
            if q == '`' and c == '$' and text[i+1] == '{':   # nested ${ } : skip balanced braces
                d = 0
                while i < len(text):
                    out.append(text[i]) if text[i] != c or d else None
                    if text[i] == '{': d += 1
                    if text[i] == '}':
                        d -= 1
                        if d == 0: break
                    i += 1
                i += 1; continue
            if c == q: q = None
        else:
            if c in '\'"`': q = c; out.append(c)
            elif c in '([{': depth += 1; out.append(c)
            elif c in ')]}': depth -= 1; out.append(c)
            elif c == ';' and depth <= 0: break
            elif c == '\n' and depth <= 0 and out and ''.join(out).strip() and not ''.join(out).rstrip().endswith(('+', '(', ',', '?', ':', '`')): break
            else: out.append(c)
        i += 1
    return ''.join(out).strip()

def interps(s):
    res, i = [], 0
    while True:
        j = s.find('${', i)
        if j < 0: break
        d, k = 0, j + 1
        while k < len(s):
            if s[k] == '{': d += 1
            elif s[k] == '}':
                d -= 1
                if d == 0: break
            k += 1
        res.append(s[j+2:k].strip()); i = k + 1
    return res

NUMERIC = re.compile(r'\.toFixed\(|Math\.|\.length\b|Number\(|parseInt|parseFloat|\bscore\b|\bpct\b|\bpercent\b|\bcount\b|\bsize\b|Date\(|\.toLocale|\bi\b$|\bidx\b|\bn\b$|\.id\b|Index', re.I)
def unsafe(exprs):
    bad = []
    for e in exprs:
        if e.startswith('esc(') or e.startswith('UI.esc(') or e.startswith('TrusionApp.esc('): continue
        if re.fullmatch(r"[\w.\[\]]*\s*\?\s*'[^']*'\s*:\s*'[^']*'", e) or re.fullmatch(r"[\w.]+\s*\?\s*\"[^\"]*\"\s*:\s*\"[^\"]*\"", e): continue   # ternary of constants
        if NUMERIC.search(e) and not re.search(r'esc\(', e): continue
        bad.append(e)
    return bad

# function bodies: UI.name = function(...){ ... }  /  name(...) { ... } returning templates
ui = {}
for m in re.finditer(r'\n\s*(UI\.[A-Za-z0-9_]+)\s*=\s*function', text):
    s = m.start(); nxt = re.search(r'\n\s*UI\.[A-Za-z0-9_]+\s*=\s*function', text[m.end():]); e = m.end() + (nxt.start() if nxt else 8000)
    ui[m.group(1)] = text[s:min(e, s + 20000)]

rows = []
for m in re.finditer(r'\.innerHTML\s*(\+?=)', text):
    ln = text.count('\n', 0, m.start()) + 1
    rhs = rhs_after(m.end())
    r0 = rhs.strip()
    if r0 in ("''", '""', '``'): kind, bad, via = 'clear (empty string)', [], ''
    elif re.fullmatch(r"(['\"]).*\1", r0, re.S) and '${' not in r0 and '+' not in r0: kind, bad, via = 'static literal', [], ''
    else:
        call = re.match(r'\s*(UI\.[A-Za-z0-9_]+)\(', r0)
        if call and call.group(1) in ui:
            body = ui[call.group(1)]; ex = interps(body); bad = unsafe(ex); kind = f'call {call.group(1)}'; via = f'{len(ex)} interpolations in template'
        elif '${' in r0:
            ex = interps(r0); bad = unsafe(ex); kind = 'template literal'; via = f'{len(ex)} interpolations'
        elif '+' in r0: kind, bad, via = 'string concatenation', [r0[:90]], 'concatenation (manual check)'
        else: kind, bad, via = 'other expression', [r0[:90]], ''
    rows.append((ln, kind, via, bad, r0[:70].replace('\n', ' ')))

cnt = collections.Counter()
for _, k, _, bad, _ in rows: cnt['no unescaped dynamic data' if not bad else 'HAS unescaped/unclassified interpolation'] += 1
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('# XSS audit of the original prototype (generated)\n\n')
    f.write(f'Generated by `tools/audit-innerhtml.py` from `reference/index-9.original.html`. **Heuristic triage, not proof.** It finds every `.innerHTML =`/`+=` ({len(rows)} sinks), classifies the assigned expression, and lists `${{…}}` interpolations that are neither wrapped in `esc()` nor look numeric. "Unescaped" means *not wrapped in esc()*; whether attacker-controlled data actually reaches it needs data-flow review (done manually only for the 3 confirmed cases below).\n\n')
    f.write(f'**Result:** {cnt["no unescaped dynamic data"]} sinks have no unescaped dynamic interpolation by this heuristic; {cnt["HAS unescaped/unclassified interpolation"]} have at least one that needs review.\n\n')
    f.write('Manually confirmed attacker-reachable (user input -> unescaped -> innerHTML): `r.filename` (file name of an uploaded file), `r.value` (typed phone/email, **persisted in localStorage** => stored XSS), `r.ocr`.\n\n')
    f.write('**Remediation in the migrated app:** none of these sinks exist. All rendering is React text children (no `dangerouslySetInnerHTML`/`innerHTML` anywhere in `frontend/src`, enforced by `tests/static-scan.test.ts` and exercised by `tests/xss-render.test.tsx` and the Chromium E2E test). The original HTML is kept only as `reference/` and is not served.\n\n')
    f.write('| Line | Sink kind | Detail | Unescaped / unclassified interpolations (first 3) |\n|---:|---|---|---|\n')
    for ln, k, via, bad, snip in rows:
        b = '; '.join('`' + x.replace('|', '\\|')[:60] + '`' for x in bad[:3]) + (f' (+{len(bad)-3} more)' if len(bad) > 3 else '') if bad else '—'
        f.write(f'| {ln} | {k} | {via} | {b} |\n')
print(len(rows), dict(cnt))
